"use client";

import { useEffect, useState } from "react";
import { usePriceStream } from "@/lib/usePriceStream";
import type { WatchlistEntry } from "@/lib/types";

const EM_DASH = "—";

function formatPrice(value: number | null | undefined): string {
  return value == null ? EM_DASH : `$${value.toFixed(2)}`;
}

function formatChangePercent(value: number | null | undefined): string {
  return value == null ? EM_DASH : `${value >= 0 ? "+" : ""}${value.toFixed(2)}%`;
}

export default function Home() {
  const [watchlist, setWatchlist] = useState<WatchlistEntry[]>([]);
  const { prices } = usePriceStream();

  useEffect(() => {
    fetch("/api/watchlist")
      .then((response) => response.json())
      .then((entries: WatchlistEntry[]) => setWatchlist(entries))
      .catch(() => setWatchlist([]));
  }, []);

  return (
    <div className="flex min-h-screen flex-col bg-[#0d1117] px-8 py-8 text-white">
      <h1 className="mb-1 text-2xl font-semibold">FinAlly</h1>
      <p className="mb-6 text-sm text-zinc-400">
        Prices shown are generated by a market simulator, not live exchange data.
      </p>

      <table className="w-full max-w-xl border-collapse text-sm">
        <thead>
          <tr className="border-b border-zinc-700 text-left text-zinc-400">
            <th className="py-2 pr-4">Ticker</th>
            <th className="py-2 pr-4">Price</th>
            <th className="py-2">Chg %</th>
          </tr>
        </thead>
        <tbody>
          {watchlist.map((entry) => {
            const live = prices[entry.ticker];
            const price = live?.price ?? entry.price;
            const changePercent = live?.change_percent ?? entry.change_percent;
            return (
              <tr key={entry.ticker} className="border-b border-zinc-800">
                <td className="py-2 pr-4 font-medium">{entry.ticker}</td>
                <td className="py-2 pr-4 tabular-nums">{formatPrice(price)}</td>
                <td className="py-2 tabular-nums">{formatChangePercent(changePercent)}</td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}
